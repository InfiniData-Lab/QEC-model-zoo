"""Tests for utils.croissant (Croissant 1.1 metadata generation)."""

import sys
import tempfile
import unittest
from pathlib import Path

_repo_code = Path(__file__).resolve().parent.parent
if str(_repo_code) not in sys.path:
    sys.path.insert(0, str(_repo_code))

from utils.croissant import build_dataset_croissant, generate_all, load_catalog

_REPO_ROOT = _repo_code.parent
_CATALOG_PATH = _REPO_ROOT / "datasets" / "dataset_catalog.yaml"


class TestBuildDatasetCroissant(unittest.TestCase):

    def test_rich_entry_produces_train_test_distribution_and_fields(self):
        entry = {
            "dataset_name": "Google Exp d3 Per Shot",
            "file_type": "parquet",
            "source": "google",
            "per_round": False,
            "folder_path": "datasets/Actual_Google_Exp_data/ml_data/d3",
            "target_col": "obs_flip",
            "shot_column": "shot_id",
            "n_rounds_column": "num_rounds",
            "ancillas": 8,
            "feature_sets": ["circuit", "avg"],
        }
        metadata = build_dataset_croissant(2, entry, _REPO_ROOT)

        self.assertEqual(metadata["@type"], "sc:Dataset")
        self.assertEqual(metadata["conformsTo"], "http://mlcommons.org/croissant/1.1")
        self.assertNotIn("isLiveDataset", metadata)
        self.assertEqual(len(metadata["distribution"]), 2)
        self.assertEqual(len(metadata["recordSet"]), 2)
        self.assertEqual(metadata["variableMeasured"], ["circuit", "avg"])

        train_record_set = metadata["recordSet"][0]
        field_ids = {f["@id"] for f in train_record_set["field"]}
        self.assertIn("google_exp_d3_per_shot/records_train/obs_flip", field_ids)
        self.assertIn("google_exp_d3_per_shot/records_train/shot_id", field_ids)
        self.assertIn("google_exp_d3_per_shot/records_train/num_rounds", field_ids)
        self.assertIn("google_exp_d3_per_shot/records_train/features_circuit", field_ids)

        # Files aren't present on disk in this test env, so no checksum and a
        # placeholder note explaining the contentUrl is not yet a public location.
        train_file_object = metadata["distribution"][0]
        self.assertNotIn("sha256", train_file_object)
        self.assertIn("description", train_file_object)

    def test_missing_license_on_real_dataset_adds_pending_note_not_fake_license(self):
        entry = {
            "dataset_name": "Some External Dataset",
            "folder_path": "datasets/some_external",
        }
        metadata = build_dataset_croissant(2, entry, _REPO_ROOT)
        self.assertNotIn("license", metadata)
        self.assertIn("not yet finalized", metadata["description"])

    def test_confirmed_license_sets_license_field_and_skips_pending_note(self):
        entry = {
            "dataset_name": "Some External Dataset",
            "folder_path": "datasets/some_external",
            "license": "https://creativecommons.org/licenses/by/4.0/",
            "license_note": "Attribution required per the data-use agreement.",
        }
        metadata = build_dataset_croissant(2, entry, _REPO_ROOT)
        self.assertEqual(metadata["license"], "https://creativecommons.org/licenses/by/4.0/")
        self.assertNotIn("not yet finalized", metadata["description"])
        self.assertIn("Attribution required per the data-use agreement.", metadata["description"])

    def test_live_dataset_has_no_pending_license_note(self):
        entry = {"dataset_name": "surface code generated by stim"}
        metadata = build_dataset_croissant(4, entry, _REPO_ROOT)
        self.assertNotIn("not yet finalized", metadata["description"])

    def test_minimal_live_entry_has_no_static_distribution(self):
        entry = {"dataset_name": "surface code generated by stim"}
        metadata = build_dataset_croissant(4, entry, _REPO_ROOT)

        self.assertTrue(metadata["isLiveDataset"])
        self.assertEqual(metadata["distribution"], [])
        self.assertEqual(metadata["recordSet"], [])
        self.assertTrue(metadata["description"].startswith("surface code generated by stim."))

    def test_description_punctuates_name_before_appended_facts(self):
        entry = {"dataset_name": "No Trailing Period", "source": "google"}
        metadata = build_dataset_croissant(99, entry, _REPO_ROOT)
        self.assertIn("No Trailing Period. Source: Google Quantum AI.", metadata["description"])


class TestRealCatalog(unittest.TestCase):

    def test_every_entry_in_real_catalog_builds_without_error(self):
        catalog = load_catalog(_CATALOG_PATH)
        for dataset_id, entry in catalog.items():
            metadata = build_dataset_croissant(dataset_id, entry, _REPO_ROOT)
            for key in ("@context", "@type", "name", "conformsTo", "description"):
                self.assertIn(key, metadata, f"dataset {dataset_id} missing {key!r}")


class TestGenerateAll(unittest.TestCase):

    def test_generate_all_writes_one_file_per_dataset_id(self):
        with tempfile.TemporaryDirectory() as tmp_dir:
            output_dir = Path(tmp_dir) / "croissant"
            written = generate_all(_CATALOG_PATH, output_dir, dataset_ids=[4, 6])

            self.assertEqual(len(written), 2)
            for path in written:
                self.assertTrue(path.is_file())

    def test_unknown_dataset_id_raises(self):
        with tempfile.TemporaryDirectory() as tmp_dir:
            with self.assertRaises(ValueError):
                generate_all(_CATALOG_PATH, Path(tmp_dir), dataset_ids=[999])


if __name__ == "__main__":
    unittest.main()
